def check(cond, msg):
    print(('  OK  ' if cond else '  FAIL ') + msg)
    if not cond:
        fails.append(msg)


def st(page):
    return page.evaluate('window.__mcl.state()')


def pop(page):
    if page.locator('.step-pop:not([hidden])').count():
        page.click('.step-pop [data-act=step-ok]')
        page.wait_for_timeout(80)


def click_term(page, ref):
    pop(page)
    p = page.evaluate(f'window.__mcl.termClient({json.dumps(ref)})')
    page.mouse.click(p['x'], p['y'])
    page.wait_for_timeout(120)


def wait_until(page, js, timeout=8000):
    t = time.time()
    while time.time() - t < timeout / 1000:
        if page.evaluate(js):
            return True
        page.wait_for_timeout(100)
    return False


